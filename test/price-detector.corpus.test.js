test("корпус реальных ценовых фраз разбирается как ожидается", () => {
  const failures = [];
  for (const [expected, text] of CORPUS) {
    const actual = detectPrice(text)?.value ?? null;
    if (actual !== expected) failures.push(`${expected} ≠ ${actual}: ${text}`);
  }
  assert.deepEqual(failures, []);
});

test("«стоит» больше не триггер цены", () => {
  assert.equal(detectPrice("жара стоит сегодня прям двадцать восемь плюс"), null);
  assert.equal(detectPrice("крем тысяча двести рублей стоит"), null);
  // Настоящие триггеры не задеты.
  assert.equal(detectPrice("стоимость тысяча двести")?.value, 1200);
  assert.equal(detectPrice("по стоимости восемь восемьсот")?.value, 8800);
});
